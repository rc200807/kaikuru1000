export default function NavigationDrawer() {
  const { data: session } = useSession()
  const pathname = usePathname()
  const [mobileOpen, setMobileOpen] = useState(false)
  const [userMenuOpen, setUserMenuOpen] = useState(false)
  const [chatUnread, setChatUnread] = useState(0)
  const [releaseUnread, setReleaseUnread] = useState(0)
  const userMenuRef = useRef<HTMLDivElement>(null)
  const user = session?.user as any

  // 店舗チャットの未読ルーム数（フォーカス時・定期・遷移時に更新）
  useEffect(() => {
    if (!user?.role) return
    let cancelled = false
    const load = async () => {
      try {
        const res = await fetch('/api/admin/chat/unread-count')
        if (!res.ok) return
        const data = await res.json()
        if (!cancelled) setChatUnread(data.count ?? 0)
      } catch { /* noop */ }
    }
    load()
    const timer = setInterval(() => { if (!document.hidden) load() }, 30000)
    window.addEventListener('focus', load)
    window.addEventListener('chat:activity', load)
    return () => {
      cancelled = true
      clearInterval(timer)
      window.removeEventListener('focus', load)
      window.removeEventListener('chat:activity', load)
    }
  }, [user?.role, pathname])

  // 未読リリースノート数（ダッシュボード閲覧で既読化されるとイベントで更新）
  useEffect(() => {
    if (!user?.role) return
    let cancelled = false
    const load = async () => {
      try {
        const res = await fetch('/api/admin/release-notes/unread-count')
        if (!res.ok) return
        const data = await res.json()
        if (!cancelled) setReleaseUnread(data.count ?? 0)
      } catch { /* noop */ }
    }
    load()
    window.addEventListener('focus', load)
    window.addEventListener('releasenotes:read', load)
    return () => {
      cancelled = true
      window.removeEventListener('focus', load)
      window.removeEventListener('releasenotes:read', load)
    }
  }, [user?.role, pathname])

  // Close user menu on outside click
  useEffect(() => {
    function handleClick(e: MouseEvent) {
      if (userMenuRef.current && !userMenuRef.current.contains(e.target as Node)) {
        setUserMenuOpen(false)
      }
    }
    if (userMenuOpen) document.addEventListener('mousedown', handleClick)
    return () => document.removeEventListener('mousedown', handleClick)
  }, [userMenuOpen])

  const drawerContent = (
    <div className="flex flex-col h-full">
      {/* Header branding */}
      <div className="px-4 pt-5 pb-4">
        <Link href="/admin/dashboard" className="flex items-center gap-2.5" onClick={() => setMobileOpen(false)}>
          <img src="/icon.svg" alt="買いクル" className="w-8 h-8 rounded-lg shrink-0 brightness-0 invert" />
          <div className="min-w-0">
            <p className="text-sm font-semibold text-[#ededed] truncate">買いクル</p>
            <p className="text-[10px] text-[#666666]">管理ポータル</p>
          </div>
        </Link>
      </div>

      <hr className="border-[rgba(255,255,255,0.06)] mx-4" />

      {/* Nav items */}
      <nav className="flex-1 px-3 py-2 space-y-0.5 overflow-y-auto thin-scrollbar">
        {navItems.filter(item => !item.roles || item.roles.includes(user?.role as AdminRole)).map(item => {
          const active = item.matchPrefixes
            ? item.matchPrefixes.some(p => pathname === p || pathname.startsWith(p + '/'))
            : pathname === item.href || pathname.startsWith(item.href + '/')
          return (
            <Link
              key={item.href}
              href={item.href}
              onClick={() => setMobileOpen(false)}
              className={`
                flex items-center gap-3 px-3 py-2 rounded-md text-sm transition-colors
                ${active
                  ? 'bg-[#1a1a1a] text-[#ffffff] font-semibold'
                  : 'text-[#a3a3a3] hover:bg-[#1a1a1a] hover:text-[#ededed]'
                }
              `}
            >
              <span className="flex-shrink-0">{item.icon}</span>
              <span className="flex-1">{item.label}</span>
              {item.href === '/admin/chat' && chatUnread > 0 && (
                <span className="flex-shrink-0 min-w-[18px] h-[18px] px-1.5 rounded-full bg-[#dc2626] text-white text-[10px] font-bold flex items-center justify-center">
                  {chatUnread > 99 ? '99+' : chatUnread}
                </span>
              )}
              {item.href === '/admin/dashboard' && releaseUnread > 0 && (
                <span className="flex-shrink-0 min-w-[18px] h-[18px] px-1.5 rounded-full bg-[#dc2626] text-white text-[10px] font-bold flex items-center justify-center">
                  {releaseUnread > 99 ? '99+' : releaseUnread}
                </span>
              )}
            </Link>
          )
        })}
      </nav>

      {/* User menu at bottom */}
      <div className="relative shadow-[inset_0_1px_0_0_rgba(255,255,255,0.06)]" ref={userMenuRef}>
        {/* Popup menu (opens upward) */}
        {userMenuOpen && (
          <div className="absolute bottom-full left-2 right-2 mb-1 rounded-lg bg-[#141414] shadow-[0_0_0_1px_rgba(255,255,255,0.08),0_4px_12px_rgba(0,0,0,0.4)] overflow-hidden z-50">
            <div className="py-1">
              <Link
                href="/admin/profile"
                onClick={() => { setUserMenuOpen(false); setMobileOpen(false) }}
                className="flex items-center gap-3 px-3 py-2.5 text-sm text-[#a3a3a3] hover:bg-[#1a1a1a] hover:text-[#ededed] transition-colors"
              >
                <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={1.5}>
                  <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 6a3.75 3.75 0 11-7.5 0 3.75 3.75 0 017.5 0zM4.501 20.118a7.5 7.5 0 0114.998 0A17.933 17.933 0 0112 21.75c-2.676 0-5.216-.584-7.499-1.632z" />
                </svg>
                プロフィール設定
              </Link>
              <Link
                href="/admin/settings"
                onClick={() => { setUserMenuOpen(false); setMobileOpen(false) }}
                className="flex items-center gap-3 px-3 py-2.5 text-sm text-[#a3a3a3] hover:bg-[#1a1a1a] hover:text-[#ededed] transition-colors"
              >
                <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={1.5}>
                  <path strokeLinecap="round" strokeLinejoin="round" d="M9.594 3.94c.09-.542.56-.94 1.11-.94h2.593c.55 0 1.02.398 1.11.94l.213 1.281c.063.374.313.686.645.87.074.04.147.083.22.127.324.196.72.257 1.075.124l1.217-.456a1.125 1.125 0 011.37.49l1.296 2.247a1.125 1.125 0 01-.26 1.431l-1.003.827c-.293.24-.438.613-.431.992a6.759 6.759 0 010 .255c-.007.378.138.75.43.99l1.005.828c.424.35.534.954.26 1.43l-1.298 2.247a1.125 1.125 0 01-1.369.491l-1.217-.456c-.355-.133-.75-.072-1.076.124a6.57 6.57 0 01-.22.128c-.331.183-.581.495-.644.869l-.213 1.28c-.09.543-.56.941-1.11.941h-2.594c-.55 0-1.02-.398-1.11-.94l-.213-1.281c-.062-.374-.312-.686-.644-.87a6.52 6.52 0 01-.22-.127c-.325-.196-.72-.257-1.076-.124l-1.217.456a1.125 1.125 0 01-1.369-.49l-1.297-2.247a1.125 1.125 0 01.26-1.431l1.004-.827c.292-.24.437-.613.43-.992a6.932 6.932 0 010-.255c.007-.378-.138-.75-.43-.99l-1.004-.828a1.125 1.125 0 01-.26-1.43l1.297-2.247a1.125 1.125 0 011.37-.491l1.216.456c.356.133.751.072 1.076-.124.072-.044.146-.087.22-.128.332-.183.582-.495.644-.869l.214-1.281z" />
                  <path strokeLinecap="round" strokeLinejoin="round" d="M15 12a3 3 0 11-6 0 3 3 0 016 0z" />
                </svg>
                システム設定
              </Link>
            </div>
            <hr className="border-[rgba(255,255,255,0.06)]" />
            <div className="py-1">
              <button
                onClick={() => { if (confirm('ログアウトしますか？')) signOut({ callbackUrl: '/admin/login' }) }}
                className="flex items-center gap-3 px-3 py-2.5 w-full text-sm text-[#a3a3a3] hover:bg-[#1a1a1a] hover:text-[#ededed] transition-colors"
              >
                <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={1.5}>
                  <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15m3 0l3-3m0 0l-3-3m3 3H9" />
                </svg>
                ログアウト
              </button>
            </div>
          </div>
        )}

        {/* User button */}
        <button
          onClick={() => setUserMenuOpen(!userMenuOpen)}
          className="w-full flex items-center gap-3 px-4 py-3 hover:bg-[#1a1a1a] transition-colors"
        >
          {user?.avatar ? (
            <img src={user.avatar} className="w-9 h-9 rounded-full object-cover shrink-0" alt="" />
          ) : (
            <div className="w-9 h-9 rounded-full bg-[#ffffff] flex items-center justify-center shrink-0">
              <span className="text-[#171717] text-sm font-semibold">{user?.name?.[0] ?? '?'}</span>
            </div>
          )}
          <div className="min-w-0 flex-1 text-left">
            <p className="text-sm font-medium text-[#ededed] truncate">{user?.name ?? '管理者'}</p>
            <p className="text-[10px] text-[#666666] truncate">{user?.email ?? ''}</p>
          </div>
          <svg className={`w-4 h-4 text-[#666666] shrink-0 transition-transform ${userMenuOpen ? 'rotate-180' : ''}`} fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M8 9l4-4 4 4" />
          </svg>
        </button>
      </div>
    </div>
  )

  return (
    <>
      {/* Desktop: Permanent drawer */}
      <aside className="hidden lg:block w-64 flex-shrink-0 h-screen sticky top-0 bg-[#0a0a0a] shadow-[inset_-1px_0_0_0_rgba(255,255,255,0.06)]">
        {drawerContent}
      </aside>

      {/* Mobile: Hamburger button (fixed) */}
      <button
        onClick={() => setMobileOpen(true)}
        className="lg:hidden fixed top-4 left-4 z-40 p-2 rounded-lg bg-[#0a0a0a] shadow-[0_0_0_1px_rgba(255,255,255,0.08),0_2px_8px_rgba(0,0,0,0.3)] text-[#ededed]"
        aria-label="メニューを開く"
      >
        <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor" className="w-6 h-6">
          <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
        </svg>
      </button>

      {/* Mobile: Modal drawer */}
      {mobileOpen && (
        <div className="lg:hidden fixed inset-0 z-50">
          <div
            className="absolute inset-0 bg-black/60"
            onClick={() => setMobileOpen(false)}
          />
          <aside className="absolute left-0 top-0 bottom-0 w-72 bg-[#0a0a0a] shadow-[1px_0_0_0_rgba(255,255,255,0.06),4px_0_16px_rgba(0,0,0,0.4)] animate-[slideInLeft_200ms_ease-out]">
            {drawerContent}
          </aside>
        </div>
      )}
    </>
  )
}
