/**
 * 売買契約書・請求書・見積書で共通利用する法的文言。
 * - INVOICE_NOTES: 請求（作業）に関する注意事項（5項）
 * - 特定商取引法に基づく書面（特商法書面）の各セクション
 * 文言は売買契約書メール（contract-email-template.ts）と一致させること。
 * HTML/プレーンテキストの双方を組み立てるビルダーも提供する（メール・PDF両用）。
 */

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

