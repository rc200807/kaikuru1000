/** 注意事項（5項）の HTML ブロック */
export function buildInvoiceNotesHtml(): string {
  return `
    <div style="margin-top:8px;padding-top:10px;border-top:1px solid #e5e7eb;">
      <p style="margin:0 0 6px;font-size:12px;font-weight:700;color:#111827;">注意事項</p>
      <ol style="margin:0;padding-left:18px;font-size:11px;color:#4b5563;line-height:1.7;">
        ${INVOICE_NOTES.map(n => `<li style="margin-bottom:6px;">${escapeHtml(n)}</li>`).join('')}
      </ol>
    </div>`
}

/** 特定商取引法に基づく書面の HTML ブロック */
export function buildTokushohoHtml(): string {
  const sections = TOKUSHOHO_SECTIONS.map(sec => {
    const bg = sec.tone === 'warn' ? '#fef2f2' : '#f9fafb'
    const headColor = sec.tone === 'warn' ? '#7f1d1d' : '#111827'
    const body = sec.lines.map(l => `<p style="margin:4px 0;">${escapeHtml(l)}</p>`).join('')
    return `
      <div style="background:${bg};padding:10px 12px;border-radius:6px;margin-bottom:10px;${sec.tone === 'warn' ? 'color:#7f1d1d;' : ''}">
        <p style="margin:0 0 6px;font-weight:700;color:${headColor};">${escapeHtml(sec.heading)}</p>
        ${body}
      </div>`
  }).join('')
  return `
    <div style="margin-top:14px;">
      <p style="margin:0 0 8px;font-size:12px;font-weight:700;color:#111827;border-bottom:2px solid #991b1b;padding-bottom:6px;">特定商取引法に基づく書面</p>
      <div style="font-size:11px;color:#374151;line-height:1.8;">
        <div style="background:#fef2f2;padding:10px 12px;border-radius:6px;margin-bottom:10px;color:#7f1d1d;">${escapeHtml(TOKUSHOHO_INTRO)}</div>
        ${sections}
        <p style="margin:8px 0 0;text-align:center;font-size:11px;color:#6b7280;">${escapeHtml(TOKUSHOHO_FOOTER)}</p>
      </div>
    </div>`
}

/** 注意事項＋特商法書面のプレーンテキスト行 */
export function buildLegalNoticeText(): string[] {
  const lines: string[] = []
  lines.push('【注意事項】')
  INVOICE_NOTES.forEach((n, i) => lines.push(`${i + 1}. ${n}`))
  lines.push('')
  lines.push('【特定商取引法に基づく書面】')
  lines.push(TOKUSHOHO_INTRO)
  TOKUSHOHO_SECTIONS.forEach(sec => {
    lines.push('')
    lines.push(sec.heading)
    sec.lines.forEach(l => lines.push(l))
  })
  lines.push('')
  lines.push(TOKUSHOHO_FOOTER)
  return lines
}
